const STORAGE_KEY = 'midad_makkah_platform_archive_v1';

export function getStoredHeritageData(): PlatformHeritageData {
  if (typeof window === 'undefined') return INITIAL_HERITAGE_DATA;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return INITIAL_HERITAGE_DATA;
    const parsed = JSON.parse(raw);
    const initialVocMap = new Map(INITIAL_HERITAGE_DATA.vocabulary.map((iv) => [iv.id, iv]));
    const storedVocList = Array.isArray(parsed.vocabulary) ? parsed.vocabulary : [];
    
    const mergedVoc = INITIAL_HERITAGE_DATA.vocabulary.map((initialItem) => {
      const storedItem = storedVocList.find((v: any) => v.id === initialItem.id);
      if (storedItem) {
        return {
          ...initialItem,
          ...storedItem,
          term: initialItem.term,
          category: initialItem.category,
          meaning: initialItem.meaning,
          image: initialItem.image || storedItem.image,
        };
      }
      return initialItem;
    });

    storedVocList.forEach((storedItem: any) => {
      if (!initialVocMap.has(storedItem.id)) {
        mergedVoc.push(storedItem);
      }
    });
    const mergedPlaces = (parsed.places || INITIAL_HERITAGE_DATA.places).map((p: any) => {
      if (p.id === 'plc-1') {
        return { ...p, image: SHAMIYA_HISTORIC_IMAGE };
      }
      if (p.id === 'plc-4') {
        return { ...p, image: MADDAA_HISTORIC_IMAGE };
      }
      if (p.id === 'plc-5') {
        return { ...p, image: AYN_ZUBAIDA_HISTORIC_IMAGE };
      }
      if (p.id === 'plc-6') {
        return { ...p, image: MISFALA_HISTORIC_IMAGE };
      }
      return p;
    });
    const initialGlimpsesMap = new Map(INITIAL_HERITAGE_DATA.glimpses.map((ig) => [ig.id, ig]));
    const storedGlimpsesList = Array.isArray(parsed.glimpses) ? parsed.glimpses : [];
    
    const mergedGlimpses = INITIAL_HERITAGE_DATA.glimpses.map((initialItem) => {
      const storedItem = storedGlimpsesList.find((g: any) => g.id === initialItem.id);
      if (storedItem) {
        return {
          ...storedItem,
          title: initialItem.title,
          summary: initialItem.summary,
          content: initialItem.content,
          image: initialItem.image,
          category: initialItem.category,
        };
      }
      return initialItem;
    });

    storedGlimpsesList.forEach((storedItem: any) => {
      if (!initialGlimpsesMap.has(storedItem.id)) {
        mergedGlimpses.push(storedItem);
      }
    });

    const initialVisionMap = new Map(INITIAL_HERITAGE_DATA.vision2030.map((iv) => [iv.id, iv]));
    const storedVisionList = Array.isArray(parsed.vision2030) ? parsed.vision2030 : [];
    
    const mergedVision = INITIAL_HERITAGE_DATA.vision2030.map((initialItem) => {
      const storedItem = storedVisionList.find((v: any) => v.id === initialItem.id);
      if (storedItem) {
        return {
          ...storedItem,
          title: initialItem.title,
          pillar: initialItem.pillar,
          heritageFoundation: initialItem.heritageFoundation,
          futureVision: initialItem.futureVision,
          details: initialItem.details,
          metrics: initialItem.metrics,
          image: initialItem.image,
        };
      }
      return initialItem;
    });

    storedVisionList.forEach((storedItem: any) => {
      if (!initialVisionMap.has(storedItem.id)) {
        mergedVision.push(storedItem);
      }
    });

    const initialMemoriesMap = new Map(INITIAL_HERITAGE_DATA.memories.map((im) => [im.id, im]));
    const storedMemoriesList = Array.isArray(parsed.memories) ? parsed.memories : [];
    
    const mergedMemories = INITIAL_HERITAGE_DATA.memories.map((initialItem) => {
      const storedItem = storedMemoriesList.find((m: any) => m.id === initialItem.id);
      if (storedItem) {
        return {
          ...storedItem,
          title: initialItem.title,
          narrator: initialItem.narrator,
          period: initialItem.period,
          place: initialItem.place,
          excerpt: initialItem.excerpt,
          fullNarrative: initialItem.fullNarrative,
          image: initialItem.image,
          recordingNote: initialItem.recordingNote,
        };
      }
      return initialItem;
    });

    storedMemoriesList.forEach((storedItem: any) => {
      if (!initialMemoriesMap.has(storedItem.id)) {
        mergedMemories.push(storedItem);
      }
    });

    const initialArabicMap = new Map(INITIAL_HERITAGE_DATA.arabicLanguage.map((ia) => [ia.id, ia]));
    const storedArabicList = Array.isArray(parsed.arabicLanguage) ? parsed.arabicLanguage : [];

    const mergedArabic = INITIAL_HERITAGE_DATA.arabicLanguage.map((initialItem) => {
      const storedItem = storedArabicList.find((a: any) => a.id === initialItem.id);
      if (storedItem) {
        return {
          ...storedItem,
          title: initialItem.title,
          subsection: initialItem.subsection,
          arabicText: initialItem.arabicText,
          verseDetails: initialItem.verseDetails,
          meaning: initialItem.meaning,
          linguisticContext: initialItem.linguisticContext,
          historicalContext: initialItem.historicalContext,
          example: initialItem.example,
          dialectUsage: initialItem.dialectUsage,
          reference: initialItem.reference,
          tags: initialItem.tags,
          image: initialItem.image || storedItem.image,
          badge: initialItem.badge,
        };
      }
      return initialItem;
    });

    storedArabicList.forEach((storedItem: any) => {
      if (!initialArabicMap.has(storedItem.id)) {
        mergedArabic.push(storedItem);
      }
    });

    return {
      vocabulary: mergedVoc,
      places: mergedPlaces,
      glimpses: mergedGlimpses,
      vision2030: mergedVision,
      memories: mergedMemories,
      arabicLanguage: mergedArabic,
    };
  } catch (e) {
    console.error('Error loading stored heritage data:', e);
    return INITIAL_HERITAGE_DATA;
  }
}

export function saveHeritageData(data: PlatformHeritageData): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch (e) {
    console.error('Error saving heritage data:', e);
  }
}

export function resetHeritageDataToDefault(): PlatformHeritageData {
  if (typeof window !== 'undefined') {
    localStorage.removeItem(STORAGE_KEY);
  }
  return INITIAL_HERITAGE_DATA;
}
